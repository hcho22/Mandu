#!/usr/bin/env python3
"""Write a run's audit into its Candidate Package.

Copies this run's records from the run's logs into `run-evidence/` (the
guard's tool log and WebFetch log, the last30days log, and the simulator
ledger; the logs are kept per Product, so they also hold earlier runs'
records, which are left out) and writes `run-audit.md`: every tool call by
kind, every call the guard
refused and why, every question the run tried to ask (there should be none),
the Workflow runs and subagents, the phase skills read, last30days runs, and
every simulator the run created and whether it was deleted.

Usage: audit_run.py [--config FILE]
"""

from __future__ import annotations

import argparse
import collections
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gp_common as gc  # noqa: E402


def read_jsonl(path, run_id):
    """This run's records in a log."""
    out = []
    if Path(path).is_file():
        for line in Path(path).read_text(encoding="utf-8").splitlines():
            try:
                record = json.loads(line)
            except ValueError:
                continue
            if isinstance(record, dict) and record.get("run_id") == run_id:
                out.append(record)
    return out


def summarize(cfg):
    pkg = Path(cfg["package"])
    run_id = cfg["run_id"]
    evidence = pkg / "run-evidence"
    evidence.mkdir(exist_ok=True)
    logs = {}
    for name, key in gc.RUN_LOGS.items():
        logs[key] = read_jsonl(cfg[key], run_id)
        (evidence / name).write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in logs[key]),
                                     encoding="utf-8")
    try:
        ledger = gc.read_json(Path(cfg["simulators"]))
    except (OSError, ValueError):
        ledger = {}
    devices = [d for d in ledger.get("devices", []) if d.get("run_id") == run_id]
    gc.write_json(evidence / "simulators.json", {"devices": devices})
    tools = logs["tool_log"]
    pre = [t for t in tools if t.get("event") == "pre"]
    by_tool = collections.Counter(t["tool"] for t in pre)
    denied = [t for t in pre if t.get("decision") == "deny"]
    asked = [t for t in pre if t["tool"] == "AskUserQuestion"]
    workflows = [t for t in pre if t["tool"] == "Workflow" and t.get("decision") == "allow"]
    agents = {t.get("agent_id") for t in pre if t.get("agent_id")}
    skills = sorted({t["phase_skill"] for t in pre if t.get("phase_skill")})
    sessions = [t for t in tools if t.get("event") == "session-start"]
    fetches = logs["fetch_log"]
    ok = [f for f in fetches if isinstance(f.get("code"), int) and 200 <= f["code"] < 300]
    l30 = logs["last30days_log"]
    lines = [
        "# Run audit",
        "",
        "Generated by `scripts/audit_run.py` from the guard's own logs, which every tool call of the run "
        "passed through, in the main session and in every subagent and Workflow agent.",
        "The logs are copied into `run-evidence/`.",
        "",
        "- Run: `%s`, Product %s, package `%s`." % (cfg.get("run_id"), cfg["product"], cfg["package_rel"]),
        "- Sessions: %d (a resumed run starts a new session)." % len(sessions),
        "- Tool calls: %d, by %d subagents and Workflow agents besides the main session." % (len(pre), len(agents)),
        "- Questions the run tried to ask the Founder: %d." % len(asked),
        "- Calls the guard refused: %d." % len(denied),
        "- Workflow runs: %d." % len(workflows),
        "- Pages fetched with WebFetch: %d (%d returned 2xx)." % (len(fetches), len(ok)),
        "- last30days runs: %d." % len(l30),
        "- Simulators created: %d; still present: %d." % (
            len(devices), len([d for d in devices if not d.get("deleted_at")])),
        "",
        "## Tool calls by kind",
        "",
        "| Tool | Calls |",
        "| --- | --- |",
    ]
    lines += ["| %s | %d |" % (name, count) for name, count in by_tool.most_common()]
    lines += ["", "## Phase skills read", ""]
    lines += ["- %s" % s for s in skills] or ["- none"]
    lines += ["", "## Workflow runs", ""]
    lines += ["- %s at %s" % (w.get("input"), w.get("at")) for w in workflows] or ["- none"]
    lines += ["", "## Refused calls", "", "Each is a call the run attempted and the guard refused; none ran.", ""]
    lines += ["- %s `%s`: %s" % (d.get("tool"), (d.get("input") or "")[:120].replace("`", "'"), d.get("reason"))
              for d in denied] or ["- none"]
    lines += ["", "## Simulators", ""]
    lines += ["- %s (%s): created %s, %s" % (d["name"], d["udid"], d.get("created_at"),
                                             "deleted %s" % d["deleted_at"] if d.get("deleted_at") else "NOT deleted")
              for d in devices] or ["- none"]
    (pkg / gc.AUDIT_NAME).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"tool_calls": len(pre), "denied": len(denied), "asked": len(asked), "workflows": len(workflows),
            "agents": len(agents), "phase_skills": skills, "simulators_left": len([d for d in devices if not d.get("deleted_at")])}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config")
    args = parser.parse_args(argv)
    config = args.config or os.environ.get("GR0WTHPILOT_CONFIG")
    if not config or not Path(config).is_file():
        print("no run config", file=sys.stderr)
        return 2
    print(json.dumps(summarize(gc.read_json(Path(config))), indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
